# input nama
nama = input("Masukkan Nama Anda: ").upper() # .upper() agar nama ditampilkan dengan huruf kapital semua
print(f"Nama Anda adalah {nama}")
print(f"Panjang nama Anda adalah {len(nama)} karakter ")
print(f"Nama Anda Jika dibalik adalah {nama[::-1]}")
print(f"Huruf pertama dari nama Anda adalah {nama[0]}")
print(f"Huruf terakhir dari nama Anda adalah {nama[-1]}")
# Tipe Data = Bentuk data yang digunakan untuk menyimpan informasi dalam program.

# string Tipe data string digunakan untuk menyimpan teks atau karakter.
# ditandai dengan penulisan data yang diapit oleh tanda kutip tunggal (' ') atau tanda kutip ganda (" ").
    # tidak ada perbedaan antara tanda kutip tunggal dan tanda kutip ganda, keduanya dapat digunakan secara bergantian.
# contoh
nama = "John Doe"
nama2 = 'Jane Smith'

# int Tipe data integer digunakan untuk menyimpan bilangan bulat (tanpa desimal).
# contoh
umur = 25

# float Tipe data float digunakan untuk menyimpan bilangan desimal.
# contoh
gaji = 5000.00

# boolean Tipe data boolean digunakan untuk menyimpan nilai benar (True) atau salah (False).
# contoh
menikah = False


print("Nama dengan tipe data string:", type(nama))
print("Umur dengan tipe data integer:", type(umur))
print("Gaji dengan tipe data float:", type(gaji))
print("Status Menikah dengan tipe data boolean:", type(menikah))


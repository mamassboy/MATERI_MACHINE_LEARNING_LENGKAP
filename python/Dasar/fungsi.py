# untuk menyimpan data saldo nasabah
saldo_nasabah =[150000]

# menggunakan fungsi max() untuk mencari saldo tertinggi
saldo_tertinggi = max(saldo_nasabah)
print(f"Saldo tertinggi di antara nasabah adalah: {saldo_tertinggi}")

# menggunakan fungsi min() untuk mencari saldo terendah
saLdo_terendah = min(saldo_nasabah)
print(f"Saldo terendah di antara nasabah adalah: {saLdo_terendah}")

